; ==============================================================================
; ปฏิบัติการที่ 1.3: ส่งค่ารหัสประจำตัวที่เก็บในหน่วยความจำ ทีละไบต์ผ่านพอร์ตที่ 0 (P0) โดยใช้ Loop วนซ้ำ
; รหัสนิสิต: 66362416 (นายธีรภัทร ภู่ระย้า)
; เทคนิคที่ใช้:
;   1. Register Indirect Addressing (@R0) เป็น Pointer ชี้ตำแหน่ง RAM
;   2. คำสั่ง DJNZ (Decrement and Jump if Not Zero) สำหรับนับรอบ Loop (8 ไบต์)
; ==============================================================================

    ORG 0000H       ; กำหนดจุดเริ่มต้นโปรแกรมที่ Reset Vector 0000H

    ; --- ส่วนที่ 1: บันทึกรหัสนิสิต 66362416 ลงใน RAM 30H - 37H ---
    MOV 30H, #06H
    MOV 31H, #06H
    MOV 32H, #03H
    MOV 33H, #06H
    MOV 34H, #02H
    MOV 35H, #04H
    MOV 36H, #01H
    MOV 37H, #06H

    ; --- ส่วนที่ 2: วนลูปส่งค่าออก P0 ทีละไบต์ ---
    MOV R0, #30H    ; กำหนดให้ R0 เป็น Pointer ชี้ที่ตำแหน่งเริ่มต้น RAM (30H)
    MOV R2, #8      ; กำหนดตัวนับรอบ R2 = 8 (จำนวนหลักของรหัสนิสิต)

SEND_LOOP:
    MOV A, @R0      ; นำข้อมูลจากตำแหน่ง RAM ที่ R0 ชี้อยู่ มาใส่ใน A (Indirect Addressing)
    MOV P0, A       ; ส่งข้อมูลจาก A ออกไปยัง Port 0 (P0)
    INC R0          ; เลื่อน Pointer R0 ไปยังแอดเดรสถัดไป (30H -> 31H -> ...)
    DJNZ R2, SEND_LOOP ; ลดค่า R2 ลง 1; ถ้า R2 ยังไม่เท่ากับ 0 ให้กระโดดวนกลับไปที่ SEND_LOOP

HERE:
    SJMP HERE       ; เมื่อส่งครบ 8 ไบต์แล้ว ให้วนรอที่นี่

    END
