; ==============================================================================
; ปฏิบัติการที่ 1.1: เขียนโปรแกรมเพื่อเก็บรหัสประจำตัวนิสิตลงในหน่วยความจำ
; รหัสนิสิต: 66362416 (นายธีรภัทร ภู่ระย้า)
; หน่วยความจำที่ใช้: Internal Data RAM แอดเดรส 30H - 37H (ย่าน Scratchpad RAM)
; ==============================================================================

    ORG 0000H       ; กำหนดจุดเริ่มต้นโปรแกรมที่ Reset Vector แอดเดรส 0000H

    ; --- จัดเก็บรหัสนิสิต 66362416 ทีละหลักลงใน RAM 30H ถึง 37H ---
    MOV 30H, #06H   ; บันทึกหลักที่ 1 (เลข 6) ลงใน RAM แอดเดรส 30H
    MOV 31H, #06H   ; บันทึกหลักที่ 2 (เลข 6) ลงใน RAM แอดเดรส 31H
    MOV 32H, #03H   ; บันทึกหลักที่ 3 (เลข 3) ลงใน RAM แอดเดรส 32H
    MOV 33H, #06H   ; บันทึกหลักที่ 4 (เลข 6) ลงใน RAM แอดเดรส 33H
    MOV 34H, #02H   ; บันทึกหลักที่ 5 (เลข 2) ลงใน RAM แอดเดรส 34H
    MOV 35H, #04H   ; บันทึกหลักที่ 6 (เลข 4) ลงใน RAM แอดเดรส 35H
    MOV 36H, #01H   ; บันทึกหลักที่ 7 (เลข 1) ลงใน RAM แอดเดรส 36H
    MOV 37H, #06H   ; บันทึกหลักที่ 8 (เลข 6) ลงใน RAM แอดเดรส 37H

