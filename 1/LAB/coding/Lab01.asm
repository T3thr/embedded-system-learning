; ------------------------------------------------------------------------------
; Lab 1.2: ส่งค่ารหัสนิสิตที่เก็บในหน่วยความจำ ออกพอร์ต 0 (P0) ทีละไบต์ตามลำดับ
; ------------------------------------------------------------------------------
;Lab 1.2
mov p0,01H          ; ส่งค่าจาก RAM 01H (6) ออก Port 0
mov p0,02H          ; ส่งค่าจาก RAM 02H (6) ออก Port 0
mov p0,03H          ; ส่งค่าจาก RAM 03H (3) ออก Port 0
mov p0,04H          ; ส่งค่าจาก RAM 04H (6) ออก Port 0
mov p0,05H          ; ส่งค่าจาก RAM 05H (2) ออก Port 0
mov p0,06H          ; ส่งค่าจาก RAM 06H (4) ออก Port 0
mov p0,07H          ; ส่งค่าจาก RAM 07H (1) ออก Port 0
mov p0,08H          ; ส่งค่าจาก RAM 08H (6) ออก Port 0

; ------------------------------------------------------------------------------
; Lab 1.3: ส่งค่ารหัสนิสิตออกพอร์ต 0 (P0) โดยใช้คำสั่งวนซ้ำ (Loop)
;          ใช้ R0 เป็น Pointer ชี้ตำแหน่ง RAM (Indirect Addressing @R0)
; ------------------------------------------------------------------------------
;Lab 1.3
mov r0,#01H         ; กำหนด Pointer เริ่มต้นที่ RAM 01H
loop1:
mov p0,@r0          ; ส่งค่าที่ R0 ชี้อยู่ออก Port 0
inc r0              ; เลื่อน Pointer ไปยังแอดเดรสถัดไป
cjne r0,#09H,loop1  ; ตรวจสอบว่าถึง 09H หรือยัง ถ้ายังให้วนลูปต่อ (ทำครบ 8 ตัว: 01H-08H)

; ------------------------------------------------------------------------------
; Lab 1.4: ส่งค่ารหัสนิสิตออกพอร์ต 0 (P0) โดยใช้ Stack
;          กำหนด SP = 10H, PUSH ค่าจาก 08H ถอยหลังลงมา 01H เข้า Stack (LIFO)
;          จากนั้น POP เข้า P0 จะได้ลำดับเรียงจากหลักแรกไปหลักสุดท้าย (01H -> 08H)
; ------------------------------------------------------------------------------
;Lab 1.4
mov SP,#10H         ; กำหนดค่าเริ่มต้นของ Stack Pointer ที่ 10H
mov r0,#08H         ; กำหนด Pointer เริ่มต้นที่ตำแหน่งท้ายสุด 08H
loop2:
mov B,@r0           ; อ่านค่าจาก RAM ที่ R0 ชี้ มาพักไว้ที่ Register B
PUSH B              ; ดันค่าใน B ลง Stack
dec r0              ; ลด Pointer ลงทีละ 1 (08H -> 07H -> ... -> 01H)
cjne r0,#00H,loop2  ; วนลูปจนกว่าจะครบทุกตัวถึง 01H

mov r0,#01H         ; ใช้ R0 เป็นตัวนับรอบการ POP
loop3:
POP p0              ; ดึงค่าจาก Stack ส่งออก Port 0 (ได้ค่าเรียง 01H -> 08H)
inc r0              ; เพิ่มตัวนับรอบ
cjne r0,#09H,loop3  ; วนลูป POP ครบ 8 ครั้ง

