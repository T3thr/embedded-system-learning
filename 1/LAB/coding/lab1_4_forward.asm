; ==============================================================================
; ปฏิบัติการที่ 1.4 (เวอร์ชันส่งค่าตามลำดับเดิม 6->6->3->6->2->4->1->6 ด้วย Stack)
; รหัสนิสิต: 66362416 (นายธีรภัทร ภู่ระย้า)
; แนวคิด: เพื่อให้ข้อมูลที่ POP ออกมาทาง P0 เรียงลำดับจากหลักแรกไปหลักสุดท้าย
;         เราต้องใช้สมบัติ LIFO ของ Stack โดย PUSH หลักสุดท้าย (37H) เข้าไปก่อน
;         แล้วจบด้วยหลักแรก (30H) เมื่อ POP ออกมา P0 จะได้รับหลักที่ 1 เป็นตัวแรกทันที!
; ==============================================================================

    ORG 0000H

    ; --- ส่วนที่ 1: บันทึกรหัสนิสิต 66362416 ลงใน RAM 30H - 37H ---
    MOV 30H, #06H
    MOV 31H, #06H
    MOV 32H, #03H
    MOV 33H, #06H
    MOV 34H, #02H
    MOV 35H, #04H
    MOV 36H, #01H
    MOV 37H, #06H

    ; --- ส่วนที่ 2: PUSH ย้อนจากหลักท้ายสุด (37H) ไปยังหลักแรก (30H) ---
    PUSH 37H        ; PUSH หลักที่ 8 (6)
    PUSH 36H        ; PUSH หลักที่ 7 (1)
    PUSH 35H        ; PUSH หลักที่ 6 (4)
    PUSH 34H        ; PUSH หลักที่ 5 (2)
    PUSH 33H        ; PUSH หลักที่ 4 (6)
    PUSH 32H        ; PUSH หลักที่ 3 (3)
    PUSH 31H        ; PUSH หลักที่ 2 (6)
    PUSH 30H        ; PUSH หลักที่ 1 (6)

    ; --- ส่วนที่ 3: POP ออกไปยัง Port 0 (ได้ลำดับ 6 -> 6 -> 3 -> 6 -> 2 -> 4 -> 1 -> 6 ตรงตามรหัส) ---
    POP P0          ; ได้ 06H (หลักที่ 1)
    POP P0          ; ได้ 06H (หลักที่ 2)
    POP P0          ; ได้ 03H (หลักที่ 3)
    POP P0          ; ได้ 06H (หลักที่ 4)
    POP P0          ; ได้ 02H (หลักที่ 5)
    POP P0          ; ได้ 04H (หลักที่ 6)
    POP P0          ; ได้ 01H (หลักที่ 7)
    POP P0          ; ได้ 06H (หลักที่ 8)

HERE:
    SJMP HERE

    END
