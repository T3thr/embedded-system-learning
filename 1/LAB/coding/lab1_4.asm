; ==============================================================================
; ปฏิบัติการที่ 1.4: ส่งค่ารหัสประจำตัวที่เก็บในหน่วยความจำ ทีละไบต์ผ่านพอร์ตที่ 0 (P0) โดยใช้ Stack
; รหัสนิสิต: 66362416 (นายธีรภัทร ภู่ระย้า)
; แนวคิดเกี่ยวกับ Stack ใน 8051:
;   - เริ่มต้นหลัง Reset ค่า Stack Pointer (SP) = 07H
;   - คำสั่ง PUSH direct: ฮาร์ดแวร์จะเพิ่มค่า SP = SP + 1 ก่อน แล้วนำข้อมูลไปบันทึกที่ @SP
;   - คำสั่ง POP direct:  ฮาร์ดแวร์จะอ่านข้อมูลจาก @SP มาใส่ที่ปลายทาง แล้วลดค่า SP = SP - 1
;   - พฤติกรรมของ Stack เป็นแบบ LIFO (Last-In, First-Out: ข้อมูลที่เข้าทีหลังสุดจะออกมาเป็นตัวแรก)
; ==============================================================================

    ORG 0000H       ; กำหนดจุดเริ่มต้นโปรแกรมที่ Reset Vector 0000H

    ; --- ส่วนที่ 1: บันทึกรหัสนิสิต 66362416 ลงใน RAM 30H - 37H ---
    MOV 30H, #06H   ; หลักที่ 1 (6)
    MOV 31H, #06H   ; หลักที่ 2 (6)
    MOV 32H, #03H   ; หลักที่ 3 (3)
    MOV 33H, #06H   ; หลักที่ 4 (6)
    MOV 34H, #02H   ; หลักที่ 5 (2)
    MOV 35H, #04H   ; หลักที่ 6 (4)
    MOV 36H, #01H   ; หลักที่ 7 (1)
    MOV 37H, #06H   ; หลักที่ 8 (6)

    ; --- ส่วนที่ 2: PUSH ข้อมูลจาก RAM ลงสู่ Stack ---
    ; สังเกตค่า SP จะเพิ่มขึ้นทีละ 1 จาก 07H -> 08H -> ... -> 0FH
    PUSH 30H        ; SP = 08H, ค่าใน Stack = 06H (หลักที่ 1)
    PUSH 31H        ; SP = 09H, ค่าใน Stack = 06H (หลักที่ 2)
    PUSH 32H        ; SP = 0AH, ค่าใน Stack = 03H (หลักที่ 3)
    PUSH 33H        ; SP = 0BH, ค่าใน Stack = 06H (หลักที่ 4)
    PUSH 34H        ; SP = 0CH, ค่าใน Stack = 02H (หลักที่ 5)
    PUSH 35H        ; SP = 0DH, ค่าใน Stack = 04H (หลักที่ 6)
    PUSH 36H        ; SP = 0EH, ค่าใน Stack = 01H (หลักที่ 7)
    PUSH 37H        ; SP = 0FH, ค่าใน Stack = 06H (หลักที่ 8)

    ; --- ส่วนที่ 3: POP ข้อมูลออกจาก Stack ส่งตรงไปยัง Port 0 (P0) ---
    ; หมายเหตุ: P0 มี Direct Address คือ 80H สามารถใช้ POP P0 ได้โดยตรง
    ; สังเกตการทำงานแบบ LIFO ค่าที่ PUSH ท้ายสุดจะถูก POP ออกมาก่อน
    POP P0          ; ได้ 06H (หลักที่ 8), SP ลดเหลือ 0EH
    POP P0          ; ได้ 01H (หลักที่ 7), SP ลดเหลือ 0DH
    POP P0          ; ได้ 04H (หลักที่ 6), SP ลดเหลือ 0CH
    POP P0          ; ได้ 02H (หลักที่ 5), SP ลดเหลือ 0BH
    POP P0          ; ได้ 06H (หลักที่ 4), SP ลดเหลือ 0AH
    POP P0          ; ได้ 03H (หลักที่ 3), SP ลดเหลือ 09H
    POP P0          ; ได้ 06H (หลักที่ 2), SP ลดเหลือ 08H
    POP P0          ; ได้ 06H (หลักที่ 1), SP ลดเหลือ 07H (กลับสู่ค่าเดิม)

