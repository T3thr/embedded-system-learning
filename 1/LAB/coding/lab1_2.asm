; ปฏิบัติการที่ 1.2: ส่งค่ารหัสประจำตัวที่เก็บในหน่วยความจำ ทีละไบต์อนุกรมผ่านพอร์ตที่ 0 (P0)
; รหัสนิสิต: 66362416 (นายธีรภัทร ภู่ระย้า)
; แนวคิด: ส่งค่าที่บันทึกอยู่ใน RAM (30H-37H) ออกไปยัง Port 0 ทีละไบต์ตามลำดับแบบ Sequential
; ==============================================================================

    ORG 0000H       ; กำหนดจุดเริ่มต้นโปรแกรมที่ Reset Vector 0000H

    ; --- ส่วนที่ 1: บันทึกรหัสนิสิต 66362416 ลงใน RAM 30H - 37H ---
    MOV 30H, #06H   ; หลักที่ 1 (6)
    MOV 31H, #06H   ; หลักที่ 2 (6)
    MOV 32H, #03H   ; หลักที่ 3 (3)
    MOV 33H, #06H   ; หลักที่ 4 (6)
    MOV 34H, #02H   ; หลักที่ 5 (2)
    MOV 35H, #04H   ; หลักที่ 6 (4)
    MOV 36H, #01H   ; หลักที่ 7 (1)
    MOV 37H, #06H   ; หลักที่ 8 (6)

    ; --- ส่วนที่ 2: ดึงค่าจาก RAM ส่งออกพอร์ต P0 ทีละไบต์ตามลำดับ ---
    MOV A, 30H      ; โหลดค่าจาก RAM 30H (เลข 6) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 06H)

    MOV A, 31H      ; โหลดค่าจาก RAM 31H (เลข 6) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 06H)

    MOV A, 32H      ; โหลดค่าจาก RAM 32H (เลข 3) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 03H)

    MOV A, 33H      ; โหลดค่าจาก RAM 33H (เลข 6) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 06H)

    MOV A, 34H      ; โหลดค่าจาก RAM 34H (เลข 2) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 02H)

    MOV A, 35H      ; โหลดค่าจาก RAM 35H (เลข 4) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 04H)

    MOV A, 36H      ; โหลดค่าจาก RAM 36H (เลข 1) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 01H)

    MOV A, 37H      ; โหลดค่าจาก RAM 37H (เลข 6) เข้า Accumulator
    MOV P0, A       ; ส่งค่าออกพอร์ต 0 (P0 = 06H)

